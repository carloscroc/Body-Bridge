// ============== Type Definitions ==============

/**
 * Status of the migration process.
 */
type MigrationStatus =
  | 'pending'
  | 'running'
  | 'paused'
  | 'completed'
  | 'blocked'
  | 'failed';

/**
 * Canonical patch structure for merging duplicate exercise data.
 * Only fields that differ between duplicates and canonical are included.
 * Trainer-specific fields are excluded (canonical only).
 */
export interface CanonicalPatch {
  overview?: { from: string | null; to: string };
  benefits?: { from: string[] | null; to: string[] };
  primaryMuscles?: { from: string[] | null; to: string[] };
  secondaryMuscles?: { from: string[] | null; to: string[] };
  equipment?: { from: string[] | null; to: string[] };
  tags?: { from: string[] | null; to: string[] };
  instructions?: { from: string[] | null; to: string[] };
  sets?: { from: string | null; to: string };
  reps?: { from: string | null; to: string };
  tempo?: { from: string | null; to: string };
  rest?: { from: string | null; to: string };
  weight?: { from: string | null; to: string };
}

/**
 * Group in the canonicalization plan.
 */
export interface CanonicalizationGroup {
  groupId: string;
  canonicalExerciseId: string;
  duplicateExerciseIds: string[];
  exerciseName: string;
  canonicalPatch?: CanonicalPatch;
  preserveSourceId?: string | null;
  expectedConflicts?: string[]; // trainerIds where conflicts are expected
}

/**
 * Batch in the execution manifest.
 */
export interface CanonicalizationBatch {
  batchId: string;
  groupIds: string[];
  estimatedReads: number;
  estimatedWrites: number;
}

/**
 * Complete batch manifest for bounded execution.
 */
export interface CanonicalizationBatchManifest {
  manifestVersion: string;
  manifestHash: string;
  planHash: string;
  preflightHash: string;
  generatedAt: number;
  totalBatches: number;
  batches: CanonicalizationBatch[];
}

/**
 * Plan loaded from canonicalizationPlan.ts
 */
interface CanonicalizationPlan {
  planVersion: string;
  generatedAt: number;
  groupsHash: string;
  sourceSnapshotHash: string;
  groups: CanonicalizationGroup[];
}

/**
 * Relationship conflict detected during preflight.
 */
interface RelationshipConflict {
  trainerId: string;
  duplicateUrl: string;
  canonicalUrl: string;
}

/**
 * Page group analysis result from preflight.
 */
interface PageGroupAnalysis {
  groupId: string;
  exerciseName: string;
  canonicalExists: boolean;
  duplicatesCount: number;
  duplicatesMissing: string[];
  relationshipConflicts: RelationshipConflict[];
}

// Cached plan instance
let PLAN: CanonicalizationPlan | null = null;

/**
 * Load the generated canonicalization plan.
 * Imports from canonicalizationPlan.ts which is generated by scripts.
 */
async function loadPlan(): Promise<CanonicalizationPlan> {
  if (PLAN) {
    return PLAN;
  }
  
  // Import the generated plan module
  // Note: This requires canonicalizationPlan.ts to be generated first
  try {
    // Direct import of the generated plan module
    const planModule = await import('./canonicalizationPlan.js');
    PLAN = {
      planVersion: planModule.planVersion || '1.0.0',
      generatedAt: planModule.generatedAt || Date.now(),
      groupsHash: planModule.groupsHash || '',
      sourceSnapshotHash: planModule.sourceSnapshotHash || '',
      groups: planModule.groups || [],
    };
    return PLAN;
  } catch (error) {
    throw new Error(`Failed to load canonicalization plan: ${error}. Please run 'cd scripts/canonicalization && npm run generate' first.`);
  }
}

