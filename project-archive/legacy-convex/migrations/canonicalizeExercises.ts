/**
 * Verify canonicalization results.
 * PUBLIC QUERY - requires admin secret.
 */
export const verifyCanonicalization = query({
  args: requireAdminSecret,
  handler: async (ctx, args) => {
    assertAdminSecret(args.adminSecret);
    
    const allExercises = await ctx.db.query('exercises').collect();
    
    // Check for duplicates by name
    const nameMap = new Map<string, Doc<'exercises'>[]>();
    for (const ex of allExercises) {
      const normName = ex.name.toLowerCase().trim();
      if (!nameMap.has(normName)) {
        nameMap.set(normName, []);
      }
      nameMap.get(normName)!.push(ex);
    }
    
    const duplicates = Array.from(nameMap.entries())
      .filter(([_, exs]) => exs.length > 1)
      .map(([name, exs]) => ({ name, count: exs.length, ids: exs.map((e) => e._id) }));
    
    return {
      totalExercises: allExercises.length,
      expectedCount: 938,
      duplicatesFound: duplicates.length,
      duplicateGroups: duplicates,
      isCanonicalized: duplicates.length === 0 && allExercises.length === 938,
    };
  },
});