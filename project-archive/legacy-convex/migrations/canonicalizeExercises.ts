/**
 * Merge two trainerExercise relationships with complete field-by-field comparison.
 * Returns patch data and whether merge was blocked.
 */
async function mergeTrainerExerciseRelationships(
  canonical: Doc<'trainerExercises'>,
  duplicate: Doc<'trainerExercises'>,
  ctx: MutationCtx
): Promise<{ blocked: boolean; patch: Partial<Doc<'trainerExercises'>> }> {
  const patch: Partial<Doc<'trainerExercises'>> = {};
  let blocked = false;
  
  // videoUrl: Compare normalized hashes, block if both valid and different
  const normalizeUrl = (url: string) => url.trim().toLowerCase();
  const canonicalUrl = canonical.videoUrl ? normalizeUrl(canonical.videoUrl) : '';
  const duplicateUrl = duplicate.videoUrl ? normalizeUrl(duplicate.videoUrl) : '';
  
  if (canonicalUrl && duplicateUrl && canonicalUrl !== duplicateUrl) {
    blocked = true;
  } else if (duplicateUrl && !canonicalUrl) {
    patch.videoUrl = duplicate.videoUrl;
  }
  
  // isActive: true wins
  if (duplicate.isActive && !canonical.isActive) {
    patch.isActive = true;
  }
  
  // notionPageId: Equal → keep; Different → block
  if (canonical.notionPageId && duplicate.notionPageId && canonical.notionPageId !== duplicate.notionPageId) {
    blocked = true;
  } else if (duplicate.notionPageId && !canonical.notionPageId) {
    patch.notionPageId = duplicate.notionPageId;
  }
  
  // sourceType: Prefer non-empty; block if different and both non-empty
  if (canonical.sourceType && duplicate.sourceType && canonical.sourceType !== duplicate.sourceType) {
    blocked = true;
  } else if (duplicate.sourceType && !canonical.sourceType) {
    patch.sourceType = duplicate.sourceType;
  }
  
  // assignedAt: Keep earlier timestamp
  if (duplicate.assignedAt && (!canonical.assignedAt || duplicate.assignedAt < canonical.assignedAt)) {
    patch.assignedAt = duplicate.assignedAt;
  }
  
  // updatedAt: Keep later timestamp
  if (duplicate.updatedAt && (!canonical.updatedAt || duplicate.updatedAt > canonical.updatedAt)) {
    patch.updatedAt = duplicate.updatedAt;
  }
  
  return { blocked, patch };
}

/**
 * Build a patch object from CanonicalPatch structure.
 * Only includes fields that have a non-null 'to' value.
 */
function buildCanonicalPatch(patch: CanonicalPatch): Partial<Doc<'exercises'>> {
  const result: Partial<Doc<'exercises'>> = {};
  
  if (patch.overview?.to !== undefined && patch.overview?.to !== null) {
    result.overview = patch.overview.to;
  }
  
  if (patch.benefits?.to !== undefined && patch.benefits?.to !== null) {
    result.benefits = patch.benefits.to;
  }
  
  if (patch.primaryMuscles?.to !== undefined && patch.primaryMuscles?.to !== null) {
    result.primaryMuscles = patch.primaryMuscles.to;
  }
  
  if (patch.secondaryMuscles?.to !== undefined && patch.secondaryMuscles?.to !== null) {
    result.secondaryMuscles = patch.secondaryMuscles.to;
  }
  
  if (patch.equipment?.to !== undefined && patch.equipment?.to !== null) {
    result.equipment = patch.equipment.to;
  }
  
  if (patch.tags?.to !== undefined && patch.tags?.to !== null) {
    result.tags = patch.tags.to;
  }
  
  if (patch.instructions?.to !== undefined && patch.instructions?.to !== null) {
    result.instructions = patch.instructions.to;
  }
  
  if (patch.sets?.to !== undefined && patch.sets?.to !== null) {
    result.sets = patch.sets.to;
  }
  
  if (patch.reps?.to !== undefined && patch.reps?.to !== null) {
    result.reps = patch.reps.to;
  }
  
  if (patch.tempo?.to !== undefined && patch.tempo?.to !== null) {
    result.tempo = patch.tempo.to;
  }
  
  if (patch.rest?.to !== undefined && patch.rest?.to !== null) {
    result.rest = patch.rest.to;
  }
  
  if (patch.weight?.to !== undefined && patch.weight?.to !== null) {
    result.weight = patch.weight.to;
  }
  
  return result;
}

